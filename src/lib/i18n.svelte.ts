// UI language. French is written inline in the components and doubles as the key: t('Nouvelle note')
// returns the English below when English is on, else the French itself. `{x}` placeholders take vars.

export type Lang = 'system' | 'fr' | 'en'

const ls = (k: string) => { try { return localStorage.getItem(k) } catch { return null } }

export const i18n = $state({ lang: (ls('lang') ?? 'system') as Lang })

/** The language in effect: the OS/webview's own for 'system' (French if it is French, else English). */
export const lang = () => (i18n.lang === 'system' ? (navigator.language.toLowerCase().startsWith('fr') ? 'fr' : 'en') : i18n.lang)

export function t(fr: string, vars: Record<string, string | number> = {}) {
  const s = lang() === 'en' ? (en[fr] ?? fr) : fr
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))
}

